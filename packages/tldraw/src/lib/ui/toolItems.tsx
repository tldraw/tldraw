/**
 * The tool items for editors that get their tools from options instead of the tldraw plugins, for
 * example `<TldrawEditor tools={[...defaultTools, ...defaultShapeTools]}>` with `<TldrawUi>`.
 * `useTools` adds each one that no plugin contributed, when the editor has what it needs.
 *
 * @internal
 */
export const legacyToolItems: readonly {
	items(ctx: TLUiToolItemsContext): DefaultToolItem[]
	isAvailable(ctx: TLUiToolItemsContext): boolean
}[] = [
	{ items: selectToolItems, isAvailable: ({ editor }) => hasTool(editor, 'select') },
	{ items: handToolItems, isAvailable: ({ editor }) => hasTool(editor, 'hand') },
	{ items: eraserToolItems, isAvailable: ({ editor }) => hasTool(editor, 'eraser') },
	{ items: drawToolItems, isAvailable: ({ editor }) => hasTool(editor, 'draw') },
	{ items: geoToolItems, isAvailable: ({ editor }) => hasTool(editor, 'geo') },
	{ items: arrowToolItems, isAvailable: ({ editor }) => hasTool(editor, 'arrow') },
	{ items: lineToolItems, isAvailable: ({ editor }) => hasTool(editor, 'line') },
	{ items: frameToolItems, isAvailable: ({ editor }) => hasTool(editor, 'frame') },
	{ items: textToolItems, isAvailable: ({ editor }) => hasTool(editor, 'text') },
	{
		items: mediaToolItems,
		isAvailable: ({ editor }) => editor.hasShapeUtil('image') || editor.hasShapeUtil('video'),
	},
	{ items: noteToolItems, isAvailable: ({ editor }) => hasTool(editor, 'note') },
	{ items: laserToolItems, isAvailable: ({ editor }) => hasTool(editor, 'laser') },
	{ items: embedToolItems, isAvailable: ({ editor }) => editor.hasShapeUtil('embed') },
	{ items: highlightToolItems, isAvailable: ({ editor }) => hasTool(editor, 'highlight') },
]

function hasTool(editor: TLUiToolItemsContext['editor'], id: string) {
	return editor.root.children?.[id] !== undefined
}
